// Regenerates src/data/communityStats.ts from the community Mezastar stats API (MIT licensed).
// Run: node scripts/import-stats.mjs
import { writeFileSync } from 'node:fs';

const API = 'https://api.mezastarhub.site/api/pokemon-stats';
const OUT = new URL('../src/data/communityStats.ts', import.meta.url);

const res = await fetch(API);
if (!res.ok) throw new Error(`API answered ${res.status}`);
const { data } = await res.json();

const int = (v) => (Number.isInteger(v) && v >= 0 ? v : null);
const lines = [];
for (const r of [...data].sort((a, b) => a.tagId.localeCompare(b.tagId))) {
  if (r.statsStatus !== 'ready' || r.isPlaceholder || !r.stats) continue;
  const s = r.stats;
  const grade = r.star >= 1 && r.star <= 6 ? r.star : null;
  const category = { Physical: 'physical', Special: 'special' }[r.move?.category] ?? null;
  const move = r.move?.name && r.move?.type ? [r.move.name, r.move.type.toLowerCase(), category] : null;
  const row = [grade, int(r.pokeEne), int(s.hp), int(s.attack), int(s.defense), int(s.specialAttack), int(s.specialDefense), int(s.speed), move];
  lines.push(`  ${JSON.stringify(r.tagId)}: ${JSON.stringify(row)},`);
}

writeFileSync(
  OUT,
  `// Generated by scripts/import-stats.mjs from ${API} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { MoveCategory, PokemonType } from './types';

export const COMMUNITY_STATS_SOURCE = 'Stats: mezastarhub.site community API (https://github.com/Arzzzzy/mezatag-stats-api, MIT)';

/** [grade, pokenergy, hp, attack, defense, spAttack, spDefense, speed, [moveName, moveType, category] | null] */
export type CommunityRow = [
  number | null, number | null, number | null, number | null, number | null,
  number | null, number | null, number | null, [string, PokemonType, MoveCategory | null] | null,
];

export const COMMUNITY_STATS: Record<string, CommunityRow> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${lines.length} tags`);
